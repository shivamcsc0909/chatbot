/**
 * Smart Percentage & Multi-Match Disambiguation Engine
 */
export function analyzeUserQuery(query) {
  if (!query || typeof query !== 'string') return null;

  const rawClean = query.toLowerCase().trim().replace(/^[0-9]+[\.\-\)\s]+/, ''); // remove leading numbering like "2. "
  const tokens = rawClean.split(/[\s,?.!-]+/).filter(w => w.length > 1);

  if (tokens.length === 0) return null;

  const scoredFaqs = [];

  for (const faq of LUXURY_FAQS) {
    const qClean = faq.question.toLowerCase().replace(/^[0-9]+[\.\-\)\s]+/, '');
    
    // 1. Exact or near-exact match
    if (qClean === rawClean || qClean.includes(rawClean) || rawClean.includes(qClean)) {
      return {
        type: 'exact',
        faq: faq,
        percentage: 100
      };
    }

    // 2. Keyword & Token scoring
    let score = 0;
    const qTokens = qClean.split(/[\s,?.!-]+/).filter(w => w.length > 2);
    const kwList = faq.keywords || [];

    // Check token overlap in question
    let matchedQTokens = 0;
    for (const t of tokens) {
      if (t.length <= 2) continue;
      if (qTokens.some(qt => qt.includes(t) || t.includes(qt))) {
        matchedQTokens++;
        score += 3.0;
      }
    }

    // Check keyword list
    for (const kw of kwList) {
      const kwLower = kw.toLowerCase();
      if (rawClean.includes(kwLower) || kwLower.includes(rawClean)) {
        score += 4.0;
      } else {
        for (const t of tokens) {
          if (t.length > 2 && kwLower.includes(t)) {
            score += 1.5;
          }
        }
      }
    }

    // Check content overlap
    const ansLower = faq.answer.toLowerCase();
    for (const t of tokens) {
      if (t.length > 3 && ansLower.includes(t)) {
        score += 0.8;
      }
    }

    // Calculate match percentage
    const maxPossible = Math.max(1, (tokens.length * 3.5));
    const percentage = Math.min(99, Math.round((score / maxPossible) * 100));

    if (percentage >= 25 || score >= 2.5) {
      scoredFaqs.push({
        faq,
        score,
        percentage
      });
    }
  }

  // Sort descending
  scoredFaqs.sort((a, b) => b.score - a.score);

  if (scoredFaqs.length === 0) {
    return null;
  }

  const top = scoredFaqs[0];
  const second = scoredFaqs[1];

  // Case A: Clear single winner (Distinct high score)
  if (top.percentage >= 65 || (second && (top.score - second.score >= 3.0)) || scoredFaqs.length === 1) {
    return {
      type: 'single_match',
      faq: top.faq,
      percentage: top.percentage
    };
  }

  // Case B: Ambiguous / Multiple close matches (e.g. "story and brand", "discover", "hotel", "spa")
  const closeMatches = scoredFaqs.slice(0, 4).map(s => s.faq);
  return {
    type: 'disambiguation',
    query: query,
    matchedFaqs: closeMatches,
    topFaq: top.faq
  };
}

export function findLocalFaqAnswer(query) {
  const result = analyzeUserQuery(query);
  return result ? (result.faq || result.topFaq) : null;
}
